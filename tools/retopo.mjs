// Turn a textured reference model into a studio model (clean low-poly + color slots + weighted normals).
//   npm run retopo -- <ref.fbx|glb> <objectNameContains> <basecolor.png> <OutName> [retopo options] [--normals weighted|soft|flat] [--angle 35]
// Example:
//   npm run retopo -- ref/helmet.fbx Helmet ref/helmet_basecolor.png Helmet --classes gold:25-65,blue:185-260 --snap gold
// Output (workspace/ is git-ignored — your files stay yours):
//   workspace/retopo/<OutName>_tris.js   → import it in a model file with fromTris() (see models/samples/README.md)
//   workspace/retopo/<OutName>.glb       → open in any viewer / measure with tools/topo/audit.py
// Retopo options are passed to tools/topo/retopo.py (see the header of that file and docs/en/topology.md).
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, blender } from './lib/env.mjs';

const a = process.argv.slice(2);
if(a.length < 4){ console.log('usage: npm run retopo -- <ref.fbx|glb> <objectNameContains> <basecolor.png> <OutName> [options]'); process.exit(1); }
const [ref, key, tex, name, ...rest] = a;
const take = (k, d) => { const i = rest.indexOf(k); if(i < 0) return d; const v = rest[i + 1]; rest.splice(i, 2); return v; };
const mode = take('--normals', 'weighted'), angle = take('--angle', '35');
const dir = path.join(ROOT, 'workspace', 'retopo'); fs.mkdirSync(dir, { recursive:true });
const raw = path.join(dir, name + '_raw'), fin = path.join(dir, name);

console.log('▶ 1/2 rebuild + color (tools/topo/retopo.py)');
await blender('tools/topo/retopo.py', [path.resolve(ref), key, path.resolve(tex), raw, ...rest]);
console.log(`▶ 2/2 normals: ${mode} ${angle}° (tools/topo/normals.py)`);
await blender('tools/topo/normals.py', [fin, mode, angle, raw + '.json']);

const tris = JSON.parse(fs.readFileSync(fin + '.json', 'utf8')).tris;
fs.writeFileSync(fin + '_tris.js', `// generated by npm run retopo — do not edit by hand · [a, b, c, slot, [na, nb, nc]] three.js coords, meters\nexport const TRIS = ${JSON.stringify(tris)};\n`);
for(const f of [raw + '.json', raw + '.glb', fin + '.json']) fs.rmSync(f, { force:true });
const slots = [...new Set(tris.map(t => t[3]))];
console.log(`✔ ${tris.length} tris · slots: ${slots.join(', ')} → ${path.relative(ROOT, fin)}_tris.js`);
